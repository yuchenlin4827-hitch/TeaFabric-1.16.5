package teafabric.tools;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.TreeMap;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicLong;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Downloads everything the build needs from the official sources and records the resolved
 * paths in {@code <cache>/setup.properties}:
 *
 * <ul>
 *   <li>Minecraft client jar, official mappings, libraries and assets from Mojang
 *       (piston-meta / piston-data / libraries.minecraft.net / resources.download.minecraft.net),
 *       verified against the SHA-1 sums published in the version manifest;</li>
 *   <li>the latest stable Fabric Loader, its launch libraries (ASM, Sponge Mixin), the 1.16.5
 *       intermediary mappings and the newest Fabric API built for 1.16 from meta/maven.fabricmc.net.</li>
 * </ul>
 *
 * Nothing downloaded here may be committed or redistributed; everything lives in the git-ignored
 * cache directory.
 */
public final class Setup {
    private static final String MANIFEST = "https://piston-meta.mojang.com/mc/game/version_manifest_v2.json";
    private static final String FABRIC_META = "https://meta.fabricmc.net/v2";
    private static final String FABRIC_MAVEN = "https://maven.fabricmc.net/";

    private final Path cache;
    private final String mcVersion;
    private final String loaderVersionRequest;
    private final String fabricApiRequest;
    private final String assetMode;
    private final Properties out = new Properties();

    private Setup(Path cache, String mcVersion, String loaderVersion, String fabricApi, String assetMode) {
        this.cache = cache;
        this.mcVersion = mcVersion;
        this.loaderVersionRequest = loaderVersion;
        this.fabricApiRequest = fabricApi;
        this.assetMode = assetMode;
    }

    public static void main(String[] args) throws Exception {
        Map<String, String> opts = parseArgs(args);
        Setup setup = new Setup(
                Path.of(opts.getOrDefault("cache", ".cache")).toAbsolutePath(),
                opts.getOrDefault("minecraft", "1.16.5"),
                opts.getOrDefault("loader", "latest"),
                opts.getOrDefault("fabric-api", "latest"),
                opts.getOrDefault("assets", "default"));
        setup.run();
    }

    static Map<String, String> parseArgs(String[] args) {
        Map<String, String> opts = new TreeMap<>();
        for (String arg : args) {
            if (arg.startsWith("--") && arg.contains("=")) {
                int eq = arg.indexOf('=');
                opts.put(arg.substring(2, eq), arg.substring(eq + 1));
            } else {
                throw new IllegalArgumentException("Unexpected argument " + arg + " (expected --key=value)");
            }
        }
        return opts;
    }

    private void run() throws Exception {
        Files.createDirectories(cache);
        downloadMinecraft();
        downloadFabric();
        Path props = cache.resolve("setup.properties");
        try (Writer w = Files.newBufferedWriter(props, StandardCharsets.UTF_8)) {
            out.store(w, "Generated by teafabric.tools.Setup - do not edit");
        }
        log("Wrote " + props);
    }

    // ---------------------------------------------------------------- Minecraft

    private void downloadMinecraft() throws Exception {
        Path mcDir = cache.resolve("minecraft");
        JsonObject manifest = JsonParser.parseString(Http.getString(MANIFEST)).getAsJsonObject();
        JsonObject entry = null;
        for (JsonElement e : manifest.getAsJsonArray("versions")) {
            if (e.getAsJsonObject().get("id").getAsString().equals(mcVersion)) {
                entry = e.getAsJsonObject();
            }
        }
        if (entry == null) {
            throw new IOException("Minecraft version " + mcVersion + " not found in " + MANIFEST);
        }
        Path versionDir = mcDir.resolve("versions").resolve(mcVersion);
        Path versionJson = versionDir.resolve(mcVersion + ".json");
        Http.download(entry.get("url").getAsString(), versionJson, entry.get("sha1").getAsString());
        JsonObject version = JsonParser.parseString(Files.readString(versionJson)).getAsJsonObject();

        JsonObject downloads = version.getAsJsonObject("downloads");
        Path clientJar = versionDir.resolve(mcVersion + ".jar");
        fetch(downloads.getAsJsonObject("client"), clientJar, "client jar");
        Path mappings = versionDir.resolve("client.txt");
        fetch(downloads.getAsJsonObject("client_mappings"), mappings, "official client mappings");

        out.setProperty("minecraft.version", mcVersion);
        out.setProperty("minecraft.mainClass", version.get("mainClass").getAsString());
        out.setProperty("minecraft.versionJson", versionJson.toString());
        out.setProperty("minecraft.clientJar", clientJar.toString());
        out.setProperty("minecraft.clientMappings", mappings.toString());

        // Libraries (Java artifacts only; native classifiers are useless in a browser).
        List<String> libs = new ArrayList<>();
        Path libDir = mcDir.resolve("libraries");
        for (JsonElement e : version.getAsJsonArray("libraries")) {
            JsonObject lib = e.getAsJsonObject();
            if (!rulesAllow(lib.getAsJsonArray("rules"))) {
                continue;
            }
            JsonObject dl = lib.getAsJsonObject("downloads");
            if (dl == null || !dl.has("artifact")) {
                continue;
            }
            JsonObject artifact = dl.getAsJsonObject("artifact");
            Path target = libDir.resolve(artifact.get("path").getAsString());
            fetch(artifact, target, null);
            libs.add(lib.get("name").getAsString() + "=" + target);
        }
        out.setProperty("minecraft.libraries", String.join(";", libs));
        log("Minecraft libraries: " + libs.size());

        downloadAssets(mcDir.resolve("assets"), version.getAsJsonObject("assetIndex"));
    }

    private void downloadAssets(Path assetsDir, JsonObject assetIndex) throws Exception {
        String id = assetIndex.get("id").getAsString();
        Path indexFile = assetsDir.resolve("indexes").resolve(id + ".json");
        Http.download(assetIndex.get("url").getAsString(), indexFile, assetIndex.get("sha1").getAsString());
        out.setProperty("minecraft.assetIndex", indexFile.toString());
        out.setProperty("minecraft.assetsDir", assetsDir.toString());
        out.setProperty("minecraft.assetMode", assetMode);
        if (assetMode.equals("none")) {
            log("Skipping asset objects (--assets=none)");
            return;
        }
        JsonObject objects = JsonParser.parseString(Files.readString(indexFile))
                .getAsJsonObject().getAsJsonObject("objects");
        List<String[]> todo = new ArrayList<>();
        for (Map.Entry<String, JsonElement> e : objects.entrySet()) {
            if (!wantAsset(e.getKey())) {
                continue;
            }
            JsonObject o = e.getValue().getAsJsonObject();
            todo.add(new String[] {o.get("hash").getAsString(), e.getKey()});
        }
        log("Assets: " + todo.size() + " of " + objects.size() + " objects (mode " + assetMode + ")");
        ExecutorService pool = Executors.newFixedThreadPool(8);
        AtomicInteger done = new AtomicInteger();
        AtomicLong fetched = new AtomicLong();
        List<Future<?>> futures = new ArrayList<>();
        for (String[] item : todo) {
            futures.add(pool.submit(() -> {
                String hash = item[0];
                Path target = assetsDir.resolve("objects").resolve(hash.substring(0, 2)).resolve(hash);
                String url = "https://resources.download.minecraft.net/" + hash.substring(0, 2) + "/" + hash;
                if (Http.download(url, target, hash)) {
                    fetched.incrementAndGet();
                }
                int n = done.incrementAndGet();
                if (n % 500 == 0) {
                    log("  assets " + n + "/" + todo.size());
                }
                return null;
            }));
        }
        try {
            for (Future<?> f : futures) {
                f.get();
            }
        } finally {
            pool.shutdown();
        }
        log("Assets ready (" + fetched.get() + " newly downloaded)");
    }

    /** Music and music discs are ~250 MB and are not needed to play; download them with --assets=all. */
    private boolean wantAsset(String name) {
        if (assetMode.equals("all")) {
            return true;
        }
        return !name.startsWith("minecraft/sounds/music/") && !name.startsWith("minecraft/sounds/records/");
    }

    private static void fetch(JsonObject download, Path target, String what) throws IOException {
        boolean fetched = Http.download(download.get("url").getAsString(), target,
                download.get("sha1").getAsString());
        if (what != null) {
            log((fetched ? "Downloaded " : "Up to date: ") + what + " -> " + target);
        }
    }

    /** Evaluates Mojang library rules for a Linux host (natives are skipped separately). */
    private static boolean rulesAllow(JsonArray rules) {
        if (rules == null) {
            return true;
        }
        boolean allowed = false;
        for (JsonElement e : rules) {
            JsonObject rule = e.getAsJsonObject();
            boolean matches = true;
            if (rule.has("os")) {
                JsonObject os = rule.getAsJsonObject("os");
                matches = !os.has("name") || os.get("name").getAsString().equals("linux");
            }
            if (matches) {
                allowed = rule.get("action").getAsString().equals("allow");
            }
        }
        return allowed;
    }

    // ---------------------------------------------------------------- Fabric

    private void downloadFabric() throws Exception {
        Path maven = cache.resolve("fabric");
        String loaderVersion = loaderVersionRequest;
        if (loaderVersion.equals("latest")) {
            JsonArray loaders = JsonParser.parseString(Http.getString(FABRIC_META + "/versions/loader"))
                    .getAsJsonArray();
            for (JsonElement e : loaders) {
                if (e.getAsJsonObject().get("stable").getAsBoolean()) {
                    loaderVersion = e.getAsJsonObject().get("version").getAsString();
                    break;
                }
            }
        }
        log("Fabric Loader " + loaderVersion);
        String profileUrl = FABRIC_META + "/versions/loader/" + mcVersion + "/" + loaderVersion + "/profile/json";
        String profileText = Http.getString(profileUrl);
        Files.createDirectories(maven);
        Files.writeString(maven.resolve("profile-" + loaderVersion + ".json"), profileText);
        JsonObject profile = JsonParser.parseString(profileText).getAsJsonObject();

        List<String> classpath = new ArrayList<>();
        for (JsonElement e : profile.getAsJsonArray("libraries")) {
            JsonObject lib = e.getAsJsonObject();
            String coords = lib.get("name").getAsString();
            String base = lib.has("url") ? lib.get("url").getAsString() : FABRIC_MAVEN;
            String sha1 = lib.has("sha1") ? lib.get("sha1").getAsString() : null;
            Path target = maven.resolve(mavenPath(coords));
            boolean fetched = Http.download(ensureSlash(base) + mavenPath(coords), target, sha1);
            if (sha1 == null && fetched) {
                verifyMavenSha1(ensureSlash(base) + mavenPath(coords), target);
            }
            classpath.add(coords + "=" + target);
            if (coords.startsWith("net.fabricmc:intermediary:")) {
                out.setProperty("fabric.intermediaryJar", target.toString());
            }
            if (coords.startsWith("net.fabricmc:fabric-loader:")) {
                out.setProperty("fabric.loaderJar", target.toString());
            }
        }
        out.setProperty("fabric.loader.version", loaderVersion);
        out.setProperty("fabric.mainClass", profile.get("mainClass").getAsString());
        out.setProperty("fabric.classpath", String.join(";", classpath));
        log("Fabric launch libraries: " + classpath.size());

        String apiVersion = fabricApiRequest;
        if (apiVersion.equals("latest")) {
            String meta = Http.getString(FABRIC_MAVEN + "net/fabricmc/fabric-api/fabric-api/maven-metadata.xml");
            String series = mcVersion.substring(0, mcVersion.lastIndexOf('.') > 2
                    ? mcVersion.lastIndexOf('.') : mcVersion.length());
            Matcher m = Pattern.compile("<version>([^<]*\\+" + Pattern.quote(series) + ")</version>").matcher(meta);
            while (m.find()) {
                apiVersion = m.group(1); // maven-metadata lists versions oldest first
            }
        }
        if (!apiVersion.equals("none") && !apiVersion.equals("latest")) {
            String coords = "net.fabricmc.fabric-api:fabric-api:" + apiVersion;
            Path target = maven.resolve(mavenPath(coords));
            if (Http.download(FABRIC_MAVEN + mavenPath(coords), target, null)) {
                verifyMavenSha1(FABRIC_MAVEN + mavenPath(coords), target);
            }
            // The Maven "fabric-api" artifact is an aggregator; the actual modules are POM dependencies.
            List<String> modules = new ArrayList<>();
            modules.add(coords + "=" + target);
            String pom = Http.getString(FABRIC_MAVEN + mavenPath(coords).replaceAll("\\.jar$", ".pom"));
            Matcher dep = Pattern.compile("<dependency>\\s*<groupId>([^<]+)</groupId>\\s*<artifactId>([^<]+)"
                    + "</artifactId>\\s*<version>([^<]+)</version>\\s*<scope>(compile|runtime)</scope>").matcher(pom);
            while (dep.find()) {
                String moduleCoords = dep.group(1) + ":" + dep.group(2) + ":" + dep.group(3);
                Path moduleJar = maven.resolve(mavenPath(moduleCoords));
                if (Http.download(FABRIC_MAVEN + mavenPath(moduleCoords), moduleJar, null)) {
                    verifyMavenSha1(FABRIC_MAVEN + mavenPath(moduleCoords), moduleJar);
                }
                modules.add(moduleCoords + "=" + moduleJar);
            }
            out.setProperty("fabric.api.version", apiVersion);
            out.setProperty("fabric.api.jar", target.toString());
            out.setProperty("fabric.api.modules", String.join(";", modules));
            log("Fabric API " + apiVersion + ": " + (modules.size() - 1) + " modules");
        }
    }

    private static void verifyMavenSha1(String url, Path file) throws IOException {
        String expected = Http.getString(url + ".sha1").trim().split("\\s+")[0];
        String actual = Http.sha1(file);
        if (!expected.equalsIgnoreCase(actual)) {
            Files.delete(file);
            throw new IOException("SHA-1 mismatch for " + url + ": expected " + expected + ", got " + actual);
        }
    }

    static String mavenPath(String coords) {
        String[] p = coords.split(":");
        String file = p[1] + "-" + p[2] + (p.length > 3 ? "-" + p[3] : "") + ".jar";
        return p[0].replace('.', '/') + "/" + p[1] + "/" + p[2] + "/" + file;
    }

    private static String ensureSlash(String s) {
        return s.endsWith("/") ? s : s + "/";
    }

    static void log(String msg) {
        System.out.println("[setup] " + msg);
    }
}
